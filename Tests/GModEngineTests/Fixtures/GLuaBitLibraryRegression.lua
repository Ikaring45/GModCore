local loaded = require("bit")
assert(loaded == bit)

-- Signed 32-bit normalization and the LuaJIT 2^52 + 2^51 conversion.
assert(bit.tobit(0) == 0)
assert(bit.tobit(-0) == 0)
assert(bit.tobit(0xffffffff) == -1)
assert(bit.tobit(0x100000000) == 0)
assert(bit.tobit(2^40 + 1234) == 1234)
assert(bit.tobit(0x80000000) == -2147483648)
assert(bit.tobit(1.5) == 2)
assert(bit.tobit(2.5) == 2)
assert(bit.tobit(-1.5) == -2)
assert(bit.tobit(-2.5) == -2)
assert(bit.tobit("4294967295") == -1)
assert(bit.tobit("0xffffffff") == -1)
assert(bit.tobit("0x1.0p+8") == 256)

-- Formatting: truncation, case, zero width and GMod LuaJIT beta3's
-- byte-sized precision field.
assert(bit.tohex(1) == "00000001")
assert(bit.tohex(-1) == "ffffffff")
assert(bit.tohex(-1, -8) == "FFFFFFFF")
assert(bit.tohex(0x21, 4) == "0021")
assert(bit.tohex(0x87654321, 4) == "4321")
assert(bit.tohex(0xabcd, -4) == "ABCD")
assert(bit.tohex(123, 0) == "")
assert(bit.tohex(1, 10) == "0000000001")
local maximumPrecision = bit.tohex(1, 254)
assert(#maximumPrecision == 254 and string.sub(maximumPrecision, -1) == "1")
assert(bit.tohex(1, 255) == "1")
assert(bit.tohex(1, 256) == "1")
local wrappedPrecision = bit.tohex(1, 300)
assert(#wrappedPrecision == 44 and string.sub(wrappedPrecision, -1) == "1")

-- Unary and variadic operations always return signed 32-bit Lua numbers.
assert(bit.bnot(0) == -1)
assert(bit.bnot(-1) == 0)
assert(bit.tohex(bit.bnot(0x12345678)) == "edcba987")
assert(bit.bor(1, 2, 4, 8) == 15)
assert(bit.tohex(bit.band(0x12345678, 0xff)) == "00000078")
assert(bit.tohex(bit.band(0xffffffff, 0xff00ff00, 0x0f0f0f0f)) == "0f000f00")
assert(bit.tohex(bit.bxor(0xa5a5f0f0, 0xaa55ff00)) == "0ff00ff0")
assert(bit.bxor(1, 2, 4, 8) == 15)

-- Shift/rotate counts use only their low five bits, including negatives.
assert(bit.lshift(1, 0) == 1)
assert(bit.lshift(1, 8) == 256)
assert(bit.lshift(1, 40) == 256)
assert(bit.lshift(1, -24) == 256)
assert(bit.rshift(256, 8) == 1)
assert(bit.rshift(-256, 8) == 16777215)
assert(bit.arshift(256, 8) == 1)
assert(bit.arshift(-256, 8) == -1)
assert(bit.tohex(bit.lshift(0x87654321, 12)) == "54321000")
assert(bit.tohex(bit.rshift(0x87654321, 12)) == "00087654")
assert(bit.tohex(bit.arshift(0x87654321, 12)) == "fff87654")
assert(bit.tohex(bit.rol(0x12345678, 12)) == "45678123")
assert(bit.tohex(bit.ror(0x12345678, 12)) == "67812345")
assert(bit.rol(0x12345678, 32) == bit.tobit(0x12345678))
assert(bit.ror(0x12345678, -32) == bit.tobit(0x12345678))
assert(bit.tohex(bit.bswap(0x12345678)) == "78563412")
assert(bit.tohex(bit.bswap(0x78563412)) == "12345678")

-- Required operands and every variadic operand are type-checked.
local ok, message = pcall(bit.band)
assert(not ok and string.find(message, "bad argument #1", 1, true))
ok, message = pcall(bit.bor, 1, {})
assert(not ok and string.find(message, "bad argument #2", 1, true))
ok, message = pcall(bit.lshift, 1)
assert(not ok and string.find(message, "bad argument #2", 1, true))
ok, message = pcall(bit.tohex, 1, nil)
assert(not ok and string.find(message, "bad argument #2", 1, true))

-- Installer helpers must not leak into the GLua global namespace.
assert(_G.__gmodlua_bit_tobit == nil)
assert(_G.__gmodlua_bit_bswap == nil)
