local flags = { FCVAR_ARCHIVE, FCVAR_NOTIFY, FCVAR_REPLICATED }
local value = CreateConVar("gpad_convar_fixture", "2.5", flags, "fixture help", -10, 10)
assert(type(value) == "ConVar")
assert(TypeID(value) == TYPE_CONVAR)
assert(value:GetName() == "gpad_convar_fixture")
assert(value:GetDefault() == "2.5")
assert(value:GetHelpText() == "fixture help")
assert(value:GetMin() == -10 and value:GetMax() == 10)
assert(value:GetString() == "2.5")
assert(value:GetFloat() == 2.5)
assert(value:GetInt() == 2)
assert(value:GetBool())
assert(value:IsFlagSet(FCVAR_ARCHIVE))
assert(value:IsFlagSet(FCVAR_NOTIFY))
assert(value:IsFlagSet(FCVAR_REPLICATED))
assert(value:IsFlagSet(FCVAR_LUA_SERVER))
assert(not value:IsFlagSet(FCVAR_USERINFO))

assert(GetConVar("gpad_convar_fixture") == value)
assert(GetConVar_Internal("GPAD_CONVAR_FIXTURE") == value)
assert(GetConVarString("gpad_convar_fixture") == "2.5")
assert(GetConVarNumber("gpad_convar_fixture") == 2.5)
assert(ConVarExists("gpad_convar_fixture"))
assert(ConVarExists("GPAD_CONVAR_FIXTURE"))
assert(GetConVar("missing_convar") == nil)
assert(GetConVarString("missing_convar") == "")
assert(GetConVarNumber("missing_convar") == 0)
assert(not ConVarExists("missing_convar"))

